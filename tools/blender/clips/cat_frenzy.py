"""Frenzy - 고양이 광분. 이 파일이 이 클립의 원본이다. (리그: art/blender/cat.blend)

**왜 새로 만드는가**: 광분은 팩의 `Spin`을 빌려 썼는데, 그건 **한 발로 서서 발레처럼 한 바퀴
도는** 동작이다(2026-09-13 렌더). 「덮치기 위력이 오른다」는 성난 버프에 붙으면 춤으로 읽힌다.

**광분은 「털을 세우고 하악」으로 읽힌다.** 고양이가 성낼 때 눈에 남는 것은 **꼬리가 곧추서고
귀가 납작하게 눕는** 실루엣이다. 몸을 낮춰 앞발로 버티며 머리를 숙였다가(3~6), 고개를 치켜들며
하악(7)하고 가라앉는다. 루트는 안 건드린다 — 제자리에서 도는 Spin은 CharacterController와 따로 놀았다.

**정보 설계**: 광분 발동은 이미 전원에게 보이는 사건이다(`CatFrenzy.FrenzyFxRpc` — 소리·표정 Rabid).
**발동 순간만** 튼다(0.6초). 켜져 있는 10초 내내 자세를 유지하면 「아직 광분 중」이라는 없던 정보가 된다.

────────────────────────────────────────────────────────────────────────────
**부호는 고양이 리그를 직접 쟀다**(2026-09-13, 각 뼈 +30도 → 끝점 이동). 쥐와 같지만 **귀만 반대다**:
  body + 코 숙임   head + 코 내림   leg + 발 앞·위로   tail + 배 밑으로 말림(- 곧추세움)
  **ear + 앞으로 접힘 / - 뒤로 눕힘** ← 쥐는 +가 뒤로 눕힘. 고양이 귀는 앞·위를 향해 서 있어서다
────────────────────────────────────────────────────────────────────────────

**디딘 발 값은 풀었다**(발 메시 +1mm, 고양이 쉬는 자세 3.9mm):
    앞발  body +2 → 8.8   +6 → 21.8   +10 → 31.7   +12 → 36.2
    뒷발  body -4 → 13.3  -6 → 16.7   -10 → 20.7   -24 → 24.3   -28 → 24.1
몸통을 숙이면(+) 엉덩이가 들려 뒷발은 못 닿고, 젖히면(-) 앞발이 못 닿는다 — 그 발은 풀지 않는다.
"""
from math import cos, radians, sin

NAME = "Frenzy"

FRAME_START = 1
FRAME_END = 11

POSES = {
    # 3에서 앞으로 낮게 버티고(+10) 6까지 참는다. 7에 한 번에 젖혀(-6) 하악.
    "body":     [(1, 0.0), (3, 10.0), (6, 10.0), (7, -6.0), (9, -4.0), (11, 0.0)],
    "leg.F.L":  [(1, 0.0), (3, 31.7), (6, 31.7), (7, 4.0), (9, 2.0), (11, 0.0)],
    "leg.F.R":  [(1, 0.0), (3, 31.7), (6, 31.7), (7, 4.0), (9, 2.0), (11, 0.0)],
    "leg.B.L":  [(1, 0.0), (3, 0.0), (6, 0.0), (7, 16.7), (9, 13.3), (11, 0.0)],
    "leg.B.R":  [(1, 0.0), (3, 0.0), (6, 0.0), (7, 16.7), (9, 13.3), (11, 0.0)],
    # 숙일 때 머리를 더 숙여 노려보고(순수 코 숙임 32~34도), 7에서 치켜든다(코 들림 24도).
    "head":     [(1, 0.0), (3, 22.0), (6, 24.0), (7, -18.0), (9, -10.0), (11, 0.0)],
    # 귀는 **뒤로 납작하게**(-). 하악하는 7에서 가장 눕는다 — 몸통보다 늦게 풀린다.
    "ear.L":    [(1, 0.0), (3, -35.0), (7, -45.0), (9, -30.0), (11, 0.0)],
    "ear.R":    [(1, 0.0), (3, -35.0), (7, -45.0), (9, -30.0), (11, 0.0)],
    # 꼬리가 곧추선다(-). 뿌리가 먼저(5), 끝이 한 박 늦게(6) 선다. 가라앉을 때도 끝이 늦다.
    "tail.01":  [(1, 0.0), (3, -45.0), (5, -60.0), (8, -55.0), (10, -15.0), (11, 0.0)],
    "tail.02":  [(1, 0.0), (4, -30.0), (6, -45.0), (9, -35.0), (11, 0.0)],
}


def build(_armature_object):
    """dash.py와 같다 — rotation_mode·보간을 건드리지 않는다."""
    import bpy

    for bone_name in POSES:
        if _armature_object.pose.bones.get(bone_name) is None:
            raise SystemExit(f"포즈 본 '{bone_name}'이 없다 - 리그가 바뀌었다")

    for bone_name, frames in POSES.items():
        bone = _armature_object.pose.bones[bone_name]
        for frame, degrees in frames:
            bpy.context.scene.frame_set(frame)
            half = radians(degrees) * 0.5
            bone.rotation_quaternion = (cos(half), sin(half), 0.0, 0.0)  # (w, x, y, z)
            bone.keyframe_insert(data_path="rotation_quaternion", frame=frame)
